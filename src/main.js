const observer = new IntersectionObserver((entries) => entries.forEach((entry) => {
 if (entry.isIntersecting) entry.target.classList.add("is-visible");
}), { threshold: 0.12 });

const grid = document.querySelector("#models");
const select = document.querySelector("#modelSelect");
const filterBar = document.querySelector("#productFilters");
const activeFilters = { capacity: "all", battery: "all" };

function capacityLabelToText(value) {
 return value.replace("T", " Ton");
}

function productImage(product) {
 const src = product.images?.[0];
 return src
 ? `<img src="${src}" alt="${product.name}" loading="lazy">`
 : `<div class="product-image-placeholder"><span>${product.model}</span><small>Foto zyrtare në katalog në pritje</small></div>`;
}

function renderProduktet() {
 if (!grid) return;
 const visible = products.filter((product) => {
 const capacityMatch = activeFilters.capacity === "all" || product.capacity.includes(capacityLabelToText(activeFilters.capacity));
 const batteryMatch = activeFilters.battery === "all" || product.batteryFilter === activeFilters.battery;
 return capacityMatch && batteryMatch;
 });

 grid.innerHTML = visible.map((product) => `
 <article class="product-card reveal">
 <a href="/products/${product.slug}.html">${productImage(product)}</a>
 <div class="product-body">
 <h3>${product.name}</h3>
 <p class="manufacturer">Katalog E-Fork Kosovo</p>
 <dl><div><dt>Kapaciteti</dt><dd>${product.capacity}</dd></div><div><dt>Lartësia e ngritjes</dt><dd>${product.height}</dd></div><div><dt>Bateria</dt><dd>${product.battery}</dd></div><div><dt>Lëvizja</dt><dd>${product.drive}</dd></div></dl>
 <p>${product.description}</p>
 <div class="card-actions"><a class="btn btn-secondary" href="/products/${product.slug}.html">Shiko Detajet</a><a class="btn btn-primary" href="/?model=${encodeURIComponent(product.name)}#quote">Kërko Ofertë</a></div>
 </div>
 </article>`).join("");
 document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));
}

function renderFilters() {
 if (!filterBar) return;
 const capacities = ["1.5T", "2T", "3T", "3.5T", "4T", "5T"].filter((capacity) => products.some((product) => product.capacity.includes(capacityLabelToText(capacity))));
 const batteries = [...new Set(products.map((product) => product.batteryFilter).filter(Boolean))];
 filterBar.innerHTML = `
 <button class="filter-chip is-active" data-type="capacity" data-value="all">Të gjitha kapacitetet</button>
 ${capacities.map((capacity) => `<button class="filter-chip" data-type="capacity" data-value="${capacity}">${capacity}</button>`).join("")}
 <span class="filter-divider"></span>
 <button class="filter-chip is-active" data-type="battery" data-value="all">Të gjitha bateritë</button>
 ${batteries.map((battery) => `<button class="filter-chip" data-type="battery" data-value="${battery}">${battery}</button>`).join("")}
 `;
 filterBar.addEventListener("click", (event) => {
 const button = event.target.closest(".filter-chip");
 if (!button) return;
 activeFilters[button.dataset.type] = button.dataset.value;
 filterBar.querySelectorAll(`[data-type="${button.dataset.type}"]`).forEach((chip) => chip.classList.remove("is-active"));
 button.classList.add("is-active");
 renderProduktet();
 });
}

if (grid) {
 renderFilters();
 renderProduktet();
}

if (select) {
 select.innerHTML = `<option>Modeli</option>` + products.map((product) => `<option>${product.name}</option>`).join("");
 const requestedModel = new URLSearchParams(location.search).get("model");
 if (requestedModel) select.value = requestedModel;
}

